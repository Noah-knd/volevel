pub fn strings(lang: Language) -> &'static Strings {
    match lang {
        Language::English => &EN,
        Language::Japanese => &JA,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn translations_are_populated_and_distinct() {
        let en = strings(Language::English);
        let ja = strings(Language::Japanese);
        assert!(!en.empty_title.is_empty());
        assert!(!ja.empty_title.is_empty());
        assert_ne!(en.status_active, ja.status_active);
        assert_ne!(en.tray_quit, ja.tray_quit);
        assert_ne!(en.settings_title, ja.settings_title);
    }
}
